def format_rag_prompt(query: str, context_text: str, chat_history: str = "") -> str:
    """Combines system instructions, few-shot examples, retrieved context, and user query."""
    history_block = f"\n[ประวัติการสนทนาก่อนหน้า]:\n{chat_history}\n" if chat_history else ""
    
    prompt = f"""{SYSTEM_PROMPT}

{FEW_SHOT_EXAMPLES}

{history_block}
[เอกสารอ้างอิงคู่มือบาริสต้า]:
{context_text}

คำถามของผู้ใช้: {query}
คำตอบ:"""
    return prompt

def build_chat_messages(query: str, context_text: str, chat_history: str = "") -> List[Any]:
    """
    Constructs structured LangChain chat messages (SystemMessage + HumanMessage)
    for models that respect the system role.
    """
    history_block = f"\n[ประวัติการสนทนาก่อนหน้า]:\n{chat_history}\n" if chat_history else ""
    user_payload = f"""{FEW_SHOT_EXAMPLES}

{history_block}
[เอกสารอ้างอิงคู่มือบาริสต้า]:
{context_text}

คำถามของผู้ใช้: {query}
ตอบคำถามอย่างละเอียด ครบถ้วนทุกประเด็นย่อย โดยไม่ต้องใส่แท็กเอกสารนำหน้า:"""
    
    return [
        SystemMessage(content=SYSTEM_PROMPT),
        HumanMessage(content=user_payload)
    ]
